//   남긴 것: (1) 아래 roleWhereLabel — 헤더 검색 결과의 "레이드 전체 1위" 보조줄이 쓴다.
//                 즐겨찾기와 무관한, ROLES 데이터를 사람 말로 옮기는 함수다
//            (2) AUTH.favs 의 저장·동기화(components/auth.js) — 계정에 담아 둔 목록은
