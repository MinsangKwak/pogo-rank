// 이모지 표기 흔들림을 한 글자로 모은다 (변이 선택자 U+FE0F 유무 · 같은 뜻의 다른 이모지)
const PXI_ALIAS = {
  '⚔': '⚔️', '☀': '☀️', '🔎': '🔍', '🗡': '⚔️', '🎴': '🃏',
  '🏡': '🏠', '📗': '📕', '📘': '📕', '📙': '📕', '📖': '📕',
  '⬅': '←', '✖': '✕', '❌': '✕', '×': '✕',
};

// 같은 아이콘을 화면마다 다시 만들지 않게 만들어 둔 것을 복제해서 쓴다
const PXI_CACHE = new Map();

// 이모지 하나를 도트 아이콘 SVG 로. 표에 없으면 null — 부르는 쪽이 이모지를 그대로 쓴다
function pxIcon(emoji) {
  const key = pxIconKey(emoji);
  if (!key) return null;
  if (!PXI_CACHE.has(key)) PXI_CACHE.set(key, pxIconBuild(PXI_ART[key]));
  return PXI_CACHE.get(key).cloneNode(true);
}

// 이모지 → 표의 키. 변이 선택자(U+FE0F)를 떼고 별칭을 한 번 거친다
function pxIconKey(emoji) {
  if (typeof emoji !== 'string') return null;
  const raw = emoji.trim();
  if (PXI_ART[raw]) return raw;
  const bare = raw.replace(/️/g, '');
  if (PXI_ART[bare]) return bare;
  const alias = PXI_ALIAS[bare] ?? PXI_ALIAS[raw];
  return alias && PXI_ART[alias] ? alias : null;
}

// 격자 12줄을 SVG 로. 가로로 이어지는 같은 색 칸은 사각형 하나로 묶는다 —
// 12×12 를 칸마다 그리면 144개지만, 묶으면 스무 개 안쪽이다
function pxIconBuild(rows) {
  const NS = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('viewBox', '0 0 12 12');
  svg.setAttribute('class', 'pxi');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('shape-rendering', 'crispEdges');
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let run = 1;
      while (row[x + run] === ch) run += 1;
      const ink = PXI_INK[ch];
      if (ink) {
        const rect = document.createElementNS(NS, 'rect');
        rect.setAttribute('x', String(x));
        rect.setAttribute('y', String(y));
        rect.setAttribute('width', String(run));
        rect.setAttribute('height', '1');
        rect.setAttribute('fill', ink);
        svg.append(rect);
      }
      x += run;
    }
  });
  return svg;
}

// 버튼·배지 안을 [도트 아이콘 + 글자] 로 다시 채운다.
// 도트 그림이 없는 이모지는 이모지 그대로 넣어 둔다 — 빈 버튼이 되는 것보다 낫다
function pxIconLabel(node, emoji, text = '') {
  if (!node) return node;
  node.replaceChildren(pxIcon(emoji) ?? emoji, ...(text ? [` ${text}`] : []));
  return node;
}

