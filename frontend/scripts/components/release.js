// 오히려 문장을 지저분하게 만들고 있었던 셈이다. 문법은 하나뿐이라 파서도 한 줄이면 된다
function releaseItemNode(text) {
  return el('li', {}, ...String(text).split('**').map((part, index) => (index % 2 ? el('b', {}, part) : part)));
}

